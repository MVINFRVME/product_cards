"""Промпт черновика карточки. Модель не получает права дописывать характеристики."""

from __future__ import annotations

from app.domain import MISSING
from app.facts import FactSet

SYSTEM_PROMPT = """Вы готовите черновик карточки товара для B2B-магазина контрольно-измерительных приборов.
Пишите по-русски, деловым языком, без рекламных превосходных степеней.
Технические значения берите только из блока «Разрешённые факты» в сообщении пользователя.
Нельзя добавлять типичные для такого прибора параметры: класс точности, питание, степень защиты, материал, ГОСТ, интерфейс, присоединение, погрешность, взрывозащиту, отраслевое применение и любые числа с единицами, которых нет в фактах.
Пометку «данных нет» ставьте только у полей из блока «Пропуски» и у характеристик, у которых в фактах уже написано «данных нет». Не перечисляйте чужие типичные параметры списком «питание / ГОСТ / IP: данных нет», если их не было во входе.
Не подставляйте правдоподобную замену и не используйте знания о производителе или серии.
Ответ — один JSON-объект без пояснений и без markdown. Поля:
{"seo_title":"","seo_description":"","search_queries":[""],"commercial_block":""}
seo_title — не длиннее 70 символов, только название, производитель и факты из списка.
seo_description — от 800 до 1200 символов. Объём набирайте пересказом разрешённых фактов и прямым перечислением пробелов. Пробелы перечислите один раз, одним предложением. Одну характеристику не повторяйте разными словами. Не заполняйте объём новыми характеристиками.
Не пишите отраслевые условия вроде «промышленные» или «нормативные» и не называйте резьбу словами (четвертьдюймовая, полудюймовая), если такой формулировки нет в фактах.
Не пишите про монтаж, установку, совместимость с другим оборудованием и надёжность конструкции: из размеров и резьбы это не следует.
search_queries — от 3 до 5 строк. Только название, производитель и известные характеристики.
commercial_block — 2–3 предложения для менеджера по продажам: кому подходит прибор и какие задачи он решает (по назначению из фактов), и какие 2–3 характеристики из фактов важны при подборе. Не повторяйте описание дословно и не называйте отрасли, среды и сферы применения, которых нет в фактах. Если назначения нет, так и напишите: по назначению данных нет.
Список характеристик в JSON не включайте: его соберёт программа из входа."""


def initial_messages(facts: FactSet) -> list[dict[str, str]]:
    """Собирает первое сообщение модели.

    Args:
        facts: Закрытый список фактов и пропусков.

    Returns:
        Сообщения chat completions: system и user.
    """
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": _user_prompt(facts)},
    ]


def repair_messages(
    facts: FactSet,
    previous: str,
    problems: list[str],
) -> list[dict[str, str]]:
    """Просит один исправленный JSON, не добавляя новых фактов.

    Args:
        facts: Те же разрешённые факты, что и в первом запросе.
        previous: Сырой предыдущий ответ модели.
        problems: Замечания проверки: длина, число запросов, чужие значения.

    Returns:
        Диалог, в котором предыдущий ответ стоит ответом ассистента.
    """
    remarks = "\n".join(f"- {item}" for item in problems)
    repair = (
        "Предыдущий ответ нельзя отдавать контент-менеджеру. Верните новый JSON той же формы.\n"
        "Не добавляйте технических значений, которых нет в разрешённых фактах. "
        f"Если факта нет, оставьте формулировку «{MISSING}».\n"
        f"Замечания:\n{remarks}"
    )
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": _user_prompt(facts)},
        {"role": "assistant", "content": previous},
        {"role": "user", "content": repair},
    ]


def _user_prompt(facts: FactSet) -> str:
    """Подставляет в запрос только переданные факты и уже найденные пропуски.

    Args:
        facts: Закрытый список. Новых характеристик здесь нет.

    Returns:
        Текст пользовательского сообщения.
    """
    product = facts.product
    spec_lines = "\n".join(f"- {item.name}: {item.value}" for item in facts.specs) or f"- {MISSING}"
    if facts.gaps:
        gap_lines = "\n".join(f"- {gap.field}: {gap.note}" for gap in facts.gaps)
    else:
        gap_lines = "- Пропусков нет."
    return (
        "Разрешённые факты:\n"
        f"Название: {product.name.strip() or MISSING}\n"
        f"Производитель: {product.manufacturer.strip() or MISSING}\n"
        f"Описание: {product.description.strip() or MISSING}\n"
        f"Характеристики:\n{spec_lines}\n\n"
        "Пропуски, которые нужно явно назвать в seo_description:\n"
        f"{gap_lines}"
    )
